"""List logos whose art is mostly dark (black/navy) so the UI can give them a light halo. Writes src/sim/logoMeta.ts."""
import numpy as np, os
from PIL import Image
D = 'public/assets/logos'
dark = []
for f in sorted(os.listdir(D)):
    a = np.array(Image.open(os.path.join(D, f)).convert('RGBA')).astype(float)
    op = a[:, :, 3] > 120
    if not op.sum(): continue
    px = a[op][:, :3]
    lum = 0.2126 * px[:, 0] + 0.7152 * px[:, 1] + 0.0722 * px[:, 2]
    near_black = (lum < 48) & (px.max(axis=1) < 105)  # black and deep navy, not red
    if near_black.mean() > 0.08: dark.append(f[:-4])
open('src/sim/logoMeta.ts', 'w').write('// Logos whose art is largely black or navy: they get a light halo so they read on the dark UI. Generated by tools/logo_meta.py.\nexport const DARK_LOGOS = new Set<string>(' + str(dark).replace("'", '"') + ');\n')
print(len(dark), 'dark logos')
